type Tab = {
  id: MesaTabId;
  label: string;
  Icon: (props: SVGProps<SVGSVGElement>) => React.ReactElement;
  adminOnly?: boolean;
};

const TABS: Tab[] = [
  { id: "itens", label: "Itens", Icon: ItensIcon },
  { id: "mesa", label: "Participantes", Icon: MesaIcon },
  { id: "pagamento", label: "Pagar", Icon: PagamentoIcon },
  { id: "historico", label: "Resumo", Icon: HistoricoIcon },
  { id: "ajustes", label: "Ajustes", Icon: AjustesIcon, adminOnly: true },
];

type MesaBottomNavProps = {
  activeTab: MesaTabId;
  onChange: (tab: MesaTabId) => void;
  isAdmin?: boolean;
};

/**
 * Navbar inferior exibido dentro de uma mesa. Mostra Itens, Mesa, Histórico e
 * Pagamento; o administrador da mesa ganha ainda a aba Ajustes (engrenagem).
 * O item ativo ganha uma linha verde no topo e exibe ícone + nome em verde;
 * os inativos mostram só o ícone em cinza.
 */
export default function MesaBottomNav({
  activeTab,
  onChange,
  isAdmin = false,
}: MesaBottomNavProps) {
  const navRef = useRef<HTMLElement>(null);

  // Publica a altura real para que a tela reserve exatamente esse espaço.
  useEffect(() => {
    const el = navRef.current;
    if (!el) return;

    const updateHeight = () => {
      document.documentElement.style.setProperty(
        "--bottom-nav-height",
        `${el.offsetHeight}px`,
      );
    };

    updateHeight();
    const observer = new ResizeObserver(updateHeight);
    observer.observe(el);

    return () => observer.disconnect();
  }, []);

  const tabs = TABS.filter((tab) => !tab.adminOnly || isAdmin);

  return (
    <nav
      ref={navRef}
      role="tablist"
      aria-label="Seções da mesa"
      className="fixed inset-x-0 bottom-0 z-40 mx-auto flex w-full max-w-[420px] items-start justify-between bg-white"
      style={{
        paddingTop: "12px",
        paddingInline: "16px",
        paddingBottom: "calc(6px + env(safe-area-inset-bottom))",
        boxShadow: "0 -4px 20px rgba(31,43,36,0.08)",
      }}
    >
      {tabs.map((tab) => {
        const isActive = activeTab === tab.id;
        const Icon = tab.Icon;

        return (
          <button
            key={tab.id}
            type="button"
            role="tab"
            aria-selected={isActive}
            aria-label={tab.label}
            onClick={() => onChange(tab.id)}
            className="font-poppins flex flex-col items-center transition active:scale-95"
            style={{ gap: "8px" }}
          >
            <span
              aria-hidden="true"
              className="rounded-full"
              style={{
                height: "3px",
                width: "2.25rem",
                background: isActive ? "#519472" : "transparent",
              }}
            />
            <span
              className="flex items-center"
              style={{
                gap: "6px",
                color: isActive ? "#519472" : "#484c52",
              }}
            >
              <Icon style={{ height: "1.5rem", width: "1.5rem" }} />
              {isActive ? (
                <span
                  className="font-medium"
                  style={{ fontSize: "0.75rem", lineHeight: "1rem" }}
                >
                  {tab.label}
                </span>
              ) : null}
            </span>
          </button>
        );
      })}
    </nav>
  );
}
